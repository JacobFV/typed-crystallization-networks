def glyph(ch: str) -> tuple[str, ...]:
    """The bitmap for a character, or the missing-glyph box."""
    return GLYPHS.get(ch, MISSING)


def covers(text: str) -> tuple[str, ...]:
    """The distinct characters of ``text`` this font has no glyph for."""
    return tuple(sorted({c for c in text if c not in GLYPHS and c not in "\n\t"}))


# ---------------------------------------------------------------------------
# Beyond ASCII
#
# Two mechanisms, because the two problems are different sizes.
#
# **Composition.** Most of Latin Europe is a letter this font already has plus a
# mark over it. Unicode says so itself, so `é` is decomposed with the stdlib and
# drawn as `e` with an acute in the leading above the line. Eleven mark bitmaps
# cover French, Spanish, Portuguese, German, Polish, Czech, Turkish, Romanian,
# the Nordic languages and more -- far better value than two hundred glyphs.
#
# **Explicit glyphs.** Greek and Cyrillic do not decompose into anything, so
# they are written out. Many of their letters are shaped exactly like Latin ones
# and are aliased rather than duplicated, which is why the table below is
# shorter than the alphabets it covers.
#
# CJK is not attempted and is not going to be: it is thousands of glyphs, each
# one needing far more than a 5x7 cell to stay legible. `covers()` reports it as
# missing, which is the honest answer, and the fidelity record on every
# rasterized episode carries that up to the caller.
# ---------------------------------------------------------------------------

