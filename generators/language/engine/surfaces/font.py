def decompose(ch: str) -> tuple[str, tuple[tuple[str, ...], ...], tuple[tuple[str, ...], ...]] | None:
    """``ch`` as a base letter this font has, plus marks above and below.

    Compatibility decomposition, so a full-width colon becomes a colon as well as
    an e-acute becoming an e. Returns ``None`` when there is nothing useful to
    decompose into -- which is the answer for CJK, and for anything else the font
    genuinely cannot draw.
    """
    nfkd = unicodedata.normalize("NFKD", ch)
    if nfkd == ch:
        return None
    base = nfkd[0]
    if base not in GLYPHS:
        return None
    above, below = [], []
    for c in nfkd[1:]:
        cp = ord(c)
        if cp in MARKS_ABOVE:
            above.append(MARKS_ABOVE[cp])
        elif cp in MARKS_BELOW:
            below.append(MARKS_BELOW[cp])
        elif unicodedata.combining(c):
            above.append(MARKS_ABOVE[0x0307])          # something is up there
    return base, tuple(above), tuple(below)


def drawable(ch: str) -> bool:
    """Whether this font can put the character on a page at all."""
    return ch in GLYPHS or decompose(ch) is not None


def _covers(text: str) -> tuple[str, ...]:
    return tuple(sorted({c for c in text if not drawable(c) and c not in "\n\t"}))


covers = _covers                                       # now composition-aware
